"""Run a small paired v0.6/v0.7 comparison on freshly generated worlds.

The worlds are generated by the locked v0.7 development harness, but their
outcomes are scored only after both engines receive the identical serialized
investigation.  The v0.6 engine is loaded from its archived source tree; the
current checkout is never relabeled as the old baseline.  This is a compact
development comparison, not a replacement for either locked evaluation.
"""

import argparse
import hashlib
import importlib
import importlib.util
import json
import sys
from pathlib import Path

import numpy as np

from upwind.engine import analyze as analyze_v07
from upwind.inference import MODEL_VERSION as V07_MODEL
from upwind.inference import PROTOCOL_VERSION as V07_PROTOCOL
from upwind.numerics import projector

ROOT = Path(__file__).resolve().parents[1]
BASELINE = ROOT / "evaluations/engine-v06/baseline-source/backend/upwind"
FAMILIES = (
    "nominal",
    "humidity_response",
    "sensor_drift",
    "changing_release",
    "two_sources",
    "spatial_background",
    "heavy_tail",
    "weather_error",
)


def _load_v06():
    name = "_upwind_v06_comparison"
    if name not in sys.modules:
        spec = importlib.util.spec_from_file_location(
            name,
            BASELINE / "__init__.py",
            submodule_search_locations=[str(BASELINE)],
        )
        module = importlib.util.module_from_spec(spec)
        sys.modules[name] = module
        spec.loader.exec_module(module)
    return importlib.import_module(name + ".engine"), importlib.import_module(
        name + ".models"
    )


def _sha256_tree(root):
    digest = hashlib.sha256()
    for path in sorted(root.rglob("*.py")):
        digest.update(str(path.relative_to(root)).encode())
        digest.update(path.read_bytes())
    return digest.hexdigest()


def _inside(point, polygon):
    """Return whether a lon/lat point is inside an axis-aligned cell polygon."""
    lon, lat = point["longitude"], point["latitude"]
    lons = [p["longitude"] for p in polygon]
    lats = [p["latitude"] for p in polygon]
    return min(lons) <= lon <= max(lons) and min(lats) <= lat <= max(lats)


def _point_from_sources(result, projection):
    sources = result.get("sources") or []
    if not sources:
        return None, None
    xy = np.array(
        [projection.transform(s["longitude"], s["latitude"]) for s in sources],
        dtype=float,
    )
    weights = np.array([s.get("weight", 0.0) for s in sources], dtype=float)
    if not np.isfinite(weights).all() or weights.sum() <= 0:
        return None, None
    weights /= weights.sum()
    mean = weights @ xy
    mode = xy[int(np.argmax(weights))]
    return mean, mode


def _metrics(result, truth):
    source = truth["source"]
    tr = projector(source["latitude"], source["longitude"])
    truth_xy = np.asarray(tr.transform(source["longitude"], source["latitude"]))
    estimate = result.get("location_estimate") or {}
    if estimate.get("posterior_mean"):
        mean = np.asarray(
            tr.transform(
                estimate["posterior_mean"]["longitude"],
                estimate["posterior_mean"]["latitude"],
            )
        )
        mode = np.asarray(
            tr.transform(
                estimate["density_mode"]["longitude"],
                estimate["density_mode"]["latitude"],
            )
        )
    else:
        mean, mode = _point_from_sources(result, tr)
    region = result.get("source_region90")
    covered = None
    area_fraction = None
    if region:
        covered = any(_inside(source, cell["polygon"]) for cell in region["cells"])
        domain = region.get("domain_area_m2", 0.0)
        area_fraction = (
            float(region.get("area_m2", 0.0) / domain) if domain > 0 else None
        )
    # v0.6 did not expose a posterior mean in its public response.  Its
    # archived engine has a location-weighted source representation, so score
    # that mean and density mode from the same public source cells.  The v0.7
    # response supplies both summaries directly.
    sources = result.get("sources") or []
    if mean is None and sources:
        xy = np.array(
            [tr.transform(s["longitude"], s["latitude"]) for s in sources],
            dtype=float,
        )
        weights = np.array([s.get("weight", 0.0) for s in sources], dtype=float)
        if np.isfinite(weights).all() and weights.sum() > 0:
            weights /= weights.sum()
            mean = weights @ xy
            mode = xy[int(np.argmax(weights))]
    return {
        "status": result.get("status"),
        "evidence_status": result.get("evidence_status"),
        "accepted": result.get("evidence_status") == "source_supported",
        "mean_error_m": None if mean is None else float(np.linalg.norm(mean - truth_xy)),
        "mode_error_m": None if mode is None else float(np.linalg.norm(mode - truth_xy)),
        "region90_covered": covered,
        "region90_area_fraction": area_fraction,
        "warnings": result.get("warnings", []),
        "externality_flags": (result.get("observability") or {})
        .get("externalities", {})
        .get("flags", []),
    }


def run(out, seeds, families):
    out = Path(out)
    if out.exists():
        raise FileExistsError("Refusing to overwrite a comparison directory")
    out.mkdir(parents=True)
    from scripts.evaluate_v07 import _world

    v06_engine, v06_models = _load_v06()
    metadata = {
        "purpose": "paired development comparison; not final evidence",
        "model_v06": "plume-robust-0.6.0",
        "model_v07": V07_MODEL,
        "protocol_v07": V07_PROTOCOL,
        "seeds": list(seeds),
        "families": list(families),
        "v06_source_sha256": _sha256_tree(BASELINE),
        "v07_source_sha256": _sha256_tree(ROOT / "backend/upwind"),
        "generator": "scripts/evaluate_v07.py::_world",
        "truth_use": "truth is used only to score this report after both fits; it is not passed to either engine",
    }
    (out / "metadata.json").write_text(json.dumps(metadata, indent=2) + "\n")
    rows = []
    for seed in seeds:
        for family in families:
            inv, truth = _world(family, seed)
            current = analyze_v07(inv)
            baseline_inv = v06_models.Investigation.model_validate(inv.model_dump())
            baseline_value = v06_engine.analyze(baseline_inv)
            baseline = (
                json.loads(baseline_value)
                if isinstance(baseline_value, str)
                else baseline_value
            )
            rows.append(
                {
                    "seed": seed,
                    "family": family,
                    "v06": _metrics(baseline, truth),
                    "v07": _metrics(current, truth),
                }
            )
    (out / "results.json").write_text(
        json.dumps(rows, indent=2, allow_nan=False) + "\n"
    )
    summary = {"attempts": len(rows), "models": {}}
    for model in ("v06", "v07"):
        values = [row[model] for row in rows]
        finite_mean = [r["mean_error_m"] for r in values if r["mean_error_m"] is not None]
        finite_mode = [r["mode_error_m"] for r in values if r["mode_error_m"] is not None]
        areas = [
            r["region90_area_fraction"]
            for r in values
            if r["region90_area_fraction"] is not None
        ]
        accepted = [r for r in values if r["accepted"]]
        summary["models"][model] = {
            "successful": sum(r["status"] == "ok" for r in values),
            "accepted": len(accepted),
            "accepted_wrong": sum(
                r["accepted"] and r["region90_covered"] is False for r in values
            ),
            "region90_covered": sum(r["region90_covered"] is True for r in values),
            "median_mean_error_m": float(np.median(finite_mean)) if finite_mean else None,
            "p90_mean_error_m": float(np.quantile(finite_mean, 0.9)) if finite_mean else None,
            "max_mean_error_m": float(np.max(finite_mean)) if finite_mean else None,
            "median_mode_error_m": float(np.median(finite_mode)) if finite_mode else None,
            "median_region90_area_fraction": float(np.median(areas)) if areas else None,
        }
    (out / "summary.json").write_text(json.dumps(summary, indent=2) + "\n")


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--out", type=Path, required=True)
    parser.add_argument("--seeds", type=int, nargs="+", default=[8_120_000, 8_120_001])
    parser.add_argument("--families", nargs="+", choices=FAMILIES, default=FAMILIES)
    args = parser.parse_args()
    run(args.out, args.seeds, args.families)
